a = 3
b = 2
print('Addition :', a + b) # => Add both answers
print('Subtraction :', a - b) # => Subtract both answers
print('Multiplication :', a * b) # => Multiples both answers
print('Division (float) :', a / b) # => Divides both var with answer in decimal form e.g 2.4
print('Division (floor) :', a // b) # => Divides both var with answer in integer form or whole number e.g 2 instead of 2.4 
print('Modulus :', a % b) # => Prints the remainder from the division of variables
print('Exponent (a^b) :', a ** b) # => prints var a raised to the power of var b



